// ABM Calculator (JavaScript)

function sum(a, b) {
    return a + b;
}

function subtraction(a, b) {
    return a - b;
}

const num1 = 10;
const num2 = 4;

console.log("=== ABM Calculator (JavaScript) ===");
console.log(`Number 1: ${num1}`);
console.log(`Number 2: ${num2}`);
console.log(`Sum:         ${num1} + ${num2} = ${sum(num1, num2)}`);
console.log(`Subtraction: ${num1} - ${num2} = ${subtraction(num1, num2)}`);
