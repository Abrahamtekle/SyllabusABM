# ABM Calculator (Python)

def sum_numbers(a, b):
    return a + b

def subtraction(a, b):
    return a - b

num1 = 10
num2 = 4

print("=== ABM Calculator (Python) ===")
print(f"Number 1: {num1}")
print(f"Number 2: {num2}")
print(f"Sum:         {num1} + {num2} = {sum_numbers(num1, num2)}")
print(f"Subtraction: {num1} - {num2} = {subtraction(num1, num2)}")
